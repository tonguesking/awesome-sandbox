const LICENSE_GROUP: { group: string; test: RegExp }[] = [
  { group: "mit", test: /^MIT/ },
  { group: "apache", test: /^Apache-2/ },
  { group: "bsd", test: /^(BSD|ISC|0BSD)/ },
  { group: "copyleft", test: /^(AGPL|GPL|LGPL|MPL|EPL|CDDL|EUPL|Mulan)/ },
];

/** Coarse license family for the facet: fine-grained SPDX ids add rows, not
 *  decisions, when the question is "can I ship this inside my product". */
export function licenseGroup(slug: string): string | undefined {
  const spdx = REPO_LICENSES[slug];
  if (!spdx) {
    return undefined;
  }
  for (const { group, test } of LICENSE_GROUP) {
    if (test.test(spdx)) {
      return group;
    }
  }
  return "other";
}

/** The license facet reads this map, so a listing with no repository simply
 *  cannot match any selected family. */
export function matchesLicense(item: Sandbox, group: string): boolean {
  return licenseGroup(item.slug) === group;
}
